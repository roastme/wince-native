#!/usr/bin/env python3
# Generate coredll thunks for Win32 names that have a populated kernel slot (psyscall.h W32_*, kwin32.c table).
# Signatures come from OAK mkfuncs.h WIN32_CALL lines. Output: coredll/thunks_w32.c
import re, sys
from pathlib import Path

R = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("..").resolve()
OAK = R / "ce5-ref/work/cd1x/OSFiles/PUBLIC/COMMON/OAK/INC"
KWIN = R / "ce5-ref/src/WINCE500/PRIVATE/WINCEOS/COREOS/NK/KERNEL/kwin32.c"
DEF = R / "ce5-ref/src/WINCE500/PRIVATE/WINCEOS/COREOS/CORE/DLL/coredll.def"
OUT = Path(__file__).resolve().parent.parent / "coredll/thunks_w32.c"
SKIP = {"LoadLibraryW", "WaitForSingleObject", "TlsCall", "GetProcessVersion", "KernelLibIoControl"}  # in thunks.c
NAMES = """CeGetCurrentTrust CeLogData CloseProcOE ConnectDebugger ConnectHdstub ConnectOsAxsT0 ConnectOsAxsT1 CreateCrit CreateThread
DebugNotify FreeLibrary FreeModFromCurrProc GetLastError GetOwnerProcess GetProcAddressW GetProcModList GetProcName
GetRealTime GetRomFileInfo GetTickCount IsPrimaryThread KernelIoControl KillAllOtherThreads LeaveCritSec LoadKernelLibrary
LoadStringW NKTerminateThread OtherThreadsRunning ProcessDetachAllDLLs QueryPerformanceCounter RefreshKernelAlarm SetRealTime
SetTimeZoneBias Sleep TakeCritSec ThreadAttachOrDetach VirtualAlloc VirtualFree VirtualQuery""".split()

psy = (OAK / "psyscall.h").read_text(errors="replace")
mk = (OAK / "mkfuncs.h").read_text(errors="replace")
kw = KWIN.read_text(errors="replace")
dfn = DEF.read_text(errors="replace")

# join backslash continuations, then pull WIN32_CALL(type, name, (args)) for each name
mk = re.sub(r"\\\s*\n", " ", mk)
out = ['// Generated by tools/gen_thunks.py. Do not edit by hand.',
       '#include <windows.h>', '#include <psyscall.h>', '']
made = []
for n in NAMES:
    if n in SKIP:
        continue
    m = re.search(r"#define W32_%s\s+(\d+)" % n, psy)
    if not m:
        continue
    slot = m.group(1)
    line = [l for l in kw.splitlines() if re.search(r"//\s*%s\b" % slot, l)]
    if not line or "(PFNVOID)0" in line[0]:
        continue
    sig = re.search(r"#define %s\s+WIN32_CALL\(\s*([^,]+?)\s*,\s*%s\s*,\s*\((.*?)\)\s*\)" % (n, n), mk)
    if not sig:
        continue
    rtype, args = sig.group(1).strip(), sig.group(2).strip()
    # function-pointer cast needs the arg list without the outer parens
    argtypes = args if args else "VOID"
    names = re.findall(r"(\w+)\s*(?:,|$)", args)  # not used for types; params are unnamed in the cast
    params = []
    depth, cur = 0, ""
    for ch in args:
        if ch == "," and depth == 0:
            params.append(cur.strip()); cur = ""
            continue
        depth += ch == "("
        depth -= ch == ")"
        cur += ch
    if cur.strip():
        params.append(cur.strip())
    # strip parameter names: keep the leading type tokens, dropping the last identifier
    ptypes = []
    for p in params:
        p = p.strip()
        if p in ("", "VOID", "void"):
            continue
        toks = p.replace("*", " * ").split()
        if len(toks) > 1 and re.match(r"^[A-Za-z_]\w*$", toks[-1]) and toks[-1] not in ("*",):
            toks = toks[:-1]
        ptypes.append(" ".join(toks).replace(" *", " *"))
    pdecl = ", ".join(ptypes) if ptypes else "VOID"
    arglist = ", ".join(re.findall(r"(\w+)\s*$", p)[0] if re.findall(r"(\w+)\s*$", p) else "" for p in params if p.strip() not in ("", "VOID", "void"))
    symbol = "xxx_" + n  # mkfuncs.h maps every name in this list to xxx_<name>
    fparams = ", ".join(f"{t} a{i}" for i, t in enumerate(ptypes))
    cargs = ", ".join(f"a{i}" for i in range(len(ptypes)))
    rt = rtype
    call = f"IMPLICIT_DECL({rt}, SH_WIN32, W32_{n}, ({pdecl}))({cargs})"
    body = f"    {call};" if rt.lower() == "void" else f"    return {call};"
    out.append(f"{rt} WINAPI {symbol}({fparams or 'VOID'}) {{\n{body}\n}}\n")
    made.append((n, slot, symbol))
OUT.write_text("\n".join(out))
print(f"wrote {OUT} with {len(made)} thunks")
for n, s, sym in made:
    print(f"  {n} slot {s} -> {sym}")
